-- Isi awal dari riwayat sesi login (idempoten).
INSERT INTO user_activity_days (activity_date, user_id)
SELECT DISTINCT (activity.ts AT TIME ZONE 'Asia/Jakarta')::date, activity.user_id
FROM (
  SELECT user_id, created_at AS ts FROM user_sessions
  UNION ALL
  SELECT user_id, last_used_at FROM user_sessions WHERE last_used_at IS NOT NULL
) activity
ON CONFLICT DO NOTHING;

