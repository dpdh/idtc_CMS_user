-- ---------------------------------------------------------------------------
-- Users, roles, sesi
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  full_name VARCHAR(150) NOT NULL CHECK (length(btrim(full_name)) > 0),
  email VARCHAR(254) NOT NULL,
  phone VARCHAR(20),
  password_hash VARCHAR(255) NOT NULL,
  photo_path TEXT,
  bio VARCHAR(200),
  city VARCHAR(120),
  address VARCHAR(500),
  gender VARCHAR(20) CHECK (gender IN ('laki-laki', 'perempuan')),
  birth_date DATE,
  occupation VARCHAR(150),
  korda_id VARCHAR(60) REFERENCES kordas(id) ON DELETE SET NULL,
  lbu_batch INTEGER CHECK (lbu_batch > 0),
  membership_type VARCHAR(20) NOT NULL DEFAULT 'free'
    CHECK (membership_type IN ('free', 'membership', 'sahabat')),
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL DEFAULT 'active'
    CHECK (status IN ('pending', 'active', 'suspended')),
  member_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
  email_verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

