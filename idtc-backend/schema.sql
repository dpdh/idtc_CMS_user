-- Skema database IDTC (IDTC mobile app).
-- Idempoten: aman dijalankan berulang (psql via database.sql, atau otomatis saat server start).
-- Konvensi mengikuti idtc-user: UUID primary key, snake_case, TIMESTAMPTZ, CHECK constraint,
-- role many-to-many (roles + user_roles), sesi sebagai hash token di user_sessions.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

