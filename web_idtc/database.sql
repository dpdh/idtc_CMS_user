CREATE TABLE IF NOT EXISTS users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  full_name VARCHAR(150) NOT NULL CHECK (length(btrim(full_name)) > 0),
  email VARCHAR(254) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  organization VARCHAR(180),
  profession VARCHAR(180),
  member_photo_path TEXT NOT NULL,
  avatar_id VARCHAR(30) NOT NULL DEFAULT 'explorer'
    CHECK (avatar_id IN ('explorer', 'engineer', 'scientist', 'creator', 'pioneer', 'visionary')),
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'active', 'suspended')),
  email_verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

